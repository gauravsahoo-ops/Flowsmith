def get_connector_auth_metadata(connector_key: str) -> Optional[ConnectorAuthMetadata]:
    """Look up authentication metadata for a specific connector."""
    entry = CONNECTOR_AUTH_CATALOG.get(connector_key)
    if not entry:
        return None
    return ConnectorAuthMetadata(connector_key=connector_key, **entry)


def list_connector_auth_metadata() -> List[ConnectorAuthMetadata]:
    """Return complete authentication metadata list across all connectors."""
    out = []
    for k, v in sorted(CONNECTOR_AUTH_CATALOG.items()):
        out.append(ConnectorAuthMetadata(connector_key=k, **v))
    return out


def get_auth_classification_summary() -> Dict[str, Any]:
    """Compute audit summary counts across the connector catalog."""
    total = len(CONNECTOR_AUTH_CATALOG)
    by_auth_method: Dict[str, int] = {}
    by_status: Dict[str, int] = {}
    requiring_credentials = 0
    no_auth = 0

    for item in CONNECTOR_AUTH_CATALOG.values():
        method_str = item["auth_method"].value if isinstance(item["auth_method"], AuthMethod) else str(item["auth_method"])
        status_str = item["status"].value if isinstance(item["status"], ImplementationStatus) else str(item["status"])
        by_auth_method[method_str] = by_auth_method.get(method_str, 0) + 1
        by_status[status_str] = by_status.get(status_str, 0) + 1
        if item["auth_method"] == AuthMethod.NONE:
            no_auth += 1
        else:
            requiring_credentials += 1

    return {
        "total_connectors_discovered": total,
        "connectors_requiring_credentials": requiring_credentials,
        "connectors_no_auth_required": no_auth,
        "breakdown_by_auth_method": by_auth_method,
        "breakdown_by_implementation_status": by_status,
    }
