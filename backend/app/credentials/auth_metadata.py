"""Authentication metadata definitions and classification for all FlowSmith connectors.

Provides machine-readable classification into standard authentication methods:
- OAuth 2.0
- OAuth 2.0 + Refresh Token
- API Key
- Bearer Token
- Basic Auth
- Username + Password
- Client ID + Client Secret
- Service Account / JWT
- Client Credentials / S2S
- Custom Header
- No authentication required
"""
from __future__ import annotations

from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class AuthMethod(str, Enum):
    OAUTH2 = "OAuth 2.0"
    OAUTH2_REFRESH = "OAuth 2.0 + Refresh Token"
    API_KEY = "API Key"
    BEARER_TOKEN = "Bearer Token"
    BASIC_AUTH = "Basic Auth"
    USERNAME_PASSWORD = "Username + Password"
    CLIENT_ID_SECRET = "Client ID + Client Secret"
    SERVICE_ACCOUNT_JWT = "Service Account / JWT"
    CLIENT_CREDENTIALS_S2S = "Client Credentials / S2S"
    CUSTOM_HEADER = "Custom Header"
    NONE = "No authentication required"


class ImplementationStatus(str, Enum):
    AVAILABLE = "available"
    COMING_SOON = "coming_soon"
    NOT_IMPLEMENTED = "not_implemented"


class ConnectorAuthMetadata(BaseModel):
    connector_key: str
    display_name: str
    category: str
    auth_method: AuthMethod
    credential_type: Optional[str] = None
    status: ImplementationStatus = ImplementationStatus.AVAILABLE
    required_fields: List[str] = Field(default_factory=list)
    optional_fields: List[str] = Field(default_factory=list)
    secret_fields: List[str] = Field(default_factory=list)
    supports_oauth: bool = False
    supports_refresh: bool = False
    supports_test: bool = True
    description: str = ""
    notes: Optional[str] = None


