"""Local filesystem object store backend (development default)."""

from __future__ import annotations

from pathlib import Path

from app.config import get_settings
from app.objectstore import ObjectStore


class LocalObjectStore(ObjectStore):
    def __init__(self, base_path: str | None = None) -> None:
        settings = get_settings()
        raw = base_path or settings.object_store_local_path
        backend_dir = Path(__file__).resolve().parents[1]  # backend root directory
        p_raw = Path(raw)
        if not p_raw.is_absolute():
            # If backend_dir / raw exists (e.g. backend/data/objects), anchor to backend_dir
            if (backend_dir / p_raw).exists() or not (Path.cwd() / p_raw).exists():
                self._base = (backend_dir / p_raw).resolve()
            else:
                self._base = (Path.cwd() / p_raw).resolve()
        else:
            self._base = p_raw.resolve()

        # Treat bucket as subdirectory when one is configured so local and
        # S3 layouts stay comparable; empty bucket → base path directly.
        if settings.object_store_bucket:
            self._base = self._base / settings.object_store_bucket

        self._base.mkdir(parents=True, exist_ok=True)

    def _path(self, object_key: str) -> Path:
        # Prevent directory traversal: object_key is always generated by the
        # server (workspace_id/uuid_filename), never user-supplied paths.
        # Still normalize to avoid accidental absolute keys.
        safe = object_key.lstrip("/").replace("..", "_")
        p = (self._base / safe).resolve()
        # Belt-and-braces containment: after resolve(), refuse anything that
        # escaped the store root (absolute keys, symlinked children, ...).
        base = self._base.resolve()
        if p != base and base not in p.parents:
            raise ValueError(f"object key escapes store root: {object_key!r}")
        return p

    def put(self, object_key: str, data: bytes, mime_type: str = "application/octet-stream") -> None:
        p = self._path(object_key)
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(data)

    def get(self, object_key: str) -> bytes:
        p = self._path(object_key)
        if p.is_file():
            return p.read_bytes()

        # Multi-location fallback search across potential host/container roots
        safe = object_key.lstrip("/").replace("..", "_")
        candidates = [
            Path(__file__).resolve().parents[1] / "data" / "objects" / safe,
            Path(__file__).resolve().parents[2] / "backend" / "data" / "objects" / safe,
            Path(__file__).resolve().parents[2] / "data" / "objects" / safe,
            Path("/app/backend/data/objects") / safe,
            Path.cwd() / "data" / "objects" / safe,
            Path.cwd() / "backend" / "data" / "objects" / safe,
        ]
        for cand in candidates:
            try:
                if cand.is_file():
                    return cand.read_bytes()
                # Check if parent directory contains a file starting with target stem
                parent = cand.parent
                if parent.is_dir():
                    stem = cand.name
                    for child in parent.iterdir():
                        if child.is_file() and child.name.startswith(stem):
                            return child.read_bytes()
            except Exception:
                continue

        # Recursive search across roots for files matching stem
        roots = [
            self._base,
            Path(__file__).resolve().parents[1] / "data" / "objects",
            Path(__file__).resolve().parents[2] / "backend" / "data" / "objects",
            Path(__file__).resolve().parents[2] / "data" / "objects",
            Path("/app/backend/data/objects"),
            Path.cwd() / "data" / "objects",
            Path.cwd() / "backend" / "data" / "objects",
        ]
        target_name = Path(safe).name
        for root in roots:
            try:
                if root.is_dir():
                    for match in root.glob(f"**/*{target_name}*"):
                        if match.is_file():
                            return match.read_bytes()
            except Exception:
                continue

        raise FileNotFoundError(object_key)

    def delete(self, object_key: str) -> bool:
        p = self._path(object_key)
        if not p.exists():
            return False
        try:
            p.unlink()
            # Prune empty parent dirs up to base (best-effort).
            cur = p.parent
            while cur != self._base and cur.is_dir() and not any(cur.iterdir()):
                cur.rmdir()
                cur = cur.parent
        except FileNotFoundError:
            return False
        return True

    def exists(self, object_key: str) -> bool:
        p = self._path(object_key)
        if p.is_file():
            return True
        safe = object_key.lstrip("/").replace("..", "_")
        candidates = [
            Path(__file__).resolve().parents[1] / "data" / "objects" / safe,
            Path(__file__).resolve().parents[2] / "backend" / "data" / "objects" / safe,
            Path(__file__).resolve().parents[2] / "data" / "objects" / safe,
            Path("/app/backend/data/objects") / safe,
            Path.cwd() / "data" / "objects" / safe,
            Path.cwd() / "backend" / "data" / "objects" / safe,
        ]
        for cand in candidates:
            try:
                if cand.is_file():
                    return True
                parent = cand.parent
                if parent.is_dir():
                    stem = cand.name
                    if any(child.is_file() and child.name.startswith(stem) for child in parent.iterdir()):
                        return True
            except Exception:
                continue

        roots = [
            self._base,
            Path(__file__).resolve().parents[1] / "data" / "objects",
            Path(__file__).resolve().parents[2] / "backend" / "data" / "objects",
            Path(__file__).resolve().parents[2] / "data" / "objects",
            Path("/app/backend/data/objects"),
            Path.cwd() / "data" / "objects",
            Path.cwd() / "backend" / "data" / "objects",
        ]
        target_name = Path(safe).name
        for root in roots:
            try:
                if root.is_dir():
                    for match in root.glob(f"**/*{target_name}*"):
                        if match.is_file():
                            return True
            except Exception:
                continue

        return False
